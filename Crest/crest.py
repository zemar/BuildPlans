"""Fusion: native vector crest, 70 mm round x 2 mm, five flush colors.
One self-contained script; embedded closed vector regions, no raster mesh.
Run from Scripts and Add-Ins. Diagnostic sidecar: crest.log.
White substrate is 1.6 mm; native colored inlays fill its top 0.4 mm.
crest.svg and mockup.png are editable/reference artwork, not runtime inputs.
"""
from pathlib import Path
from collections import Counter
import base64
import json
import logging
import math
import time
import zlib

DIAMETER_MM = 70.0
DISC_THICKNESS_MM = 2.0
INLAY_THICKNESS_MM = 0.4
PALETTE = (('White',(255,255,255)), ('Black',(0,0,0)),
           ('Brown',(151,87,33)), ('Red',(210,25,35)), ('Green',(112,166,40)))
ROOT = Path(__file__).resolve().parent
LOG_PATH = ROOT / 'crest.log'


def load_vectors():
    regions = json.loads(zlib.decompress(base64.b85decode(VECTOR_DATA_B85)))
    if {p['color'] for p in regions} != set(range(5)):
        raise ValueError('Exactly five vector colors are required.')
    for region in regions:
        if region['area'] <= 0 or not region['rings']:
            raise ValueError('Invalid vector region.')
        for ring in region['rings']:
            if len(ring) < 3 or any(math.hypot(*xy) > DIAMETER_MM/2+1e-5 for xy in ring):
                raise ValueError('Invalid closed vector contour.')
    return regions


def make_appearance(app, design, name, rgb):
    import adsk.core
    title = 'Crest '+name
    existing = design.appearances.itemByName(title)
    if existing:
        return existing
    library = app.materialLibraries.itemById('BA5EE55E-9982-449B-9D66-9F036540E140')
    seed = library.appearances.itemById('Prism-129') if library else None
    if not seed:
        raise RuntimeError('Fusion generic appearance is unavailable.')
    finish = design.appearances.addByCopy(seed,title)
    for key in ('opaque_albedo','generic_diffuse'):
        prop = adsk.core.ColorProperty.cast(finish.appearanceProperties.itemById(key))
        if prop:
            prop.hasConnectedTexture = False
            prop.value = adsk.core.Color.create(*rgb,255)
            return finish
    raise RuntimeError('Appearance has no editable base color: '+name)


def draw_ring(sketch, ring):
    import adsk.core
    # Use Fusion's exact analytic circle for the outer disc boundary.
    if len(ring)>100 and all(abs(math.hypot(x,y)-DIAMETER_MM/2)<1e-5 for x,y in ring):
        sketch.sketchCurves.sketchCircles.addByCenterRadius(
            adsk.core.Point3D.create(0,0,0),DIAMETER_MM/20)
        return
    points = [adsk.core.Point3D.create(x/10,y/10,0) for x,y in ring]
    lines = sketch.sketchCurves.sketchLines
    first = lines.addByTwoPoints(points[0],points[1])
    end = first.endSketchPoint
    for point in points[2:]:
        end = lines.addByTwoPoints(end,point).endSketchPoint
    lines.addByTwoPoints(end,first.startSketchPoint)


def select_profiles(sketch, regions, logger):
    """Match profile area AND centroid moments, including concave/holey regions.

    Centroids need not lie inside a region, so point sampling is not used.
    This excludes profiles corresponding to holes and unrelated nested loops.
    """
    import adsk.core
    import adsk.fusion
    candidates = []
    for profile in sketch.profiles:
        props = profile.areaProperties(adsk.fusion.CalculationAccuracy.HighCalculationAccuracy)
        candidates.append((profile,props.area*100,props.centroid.x*10,props.centroid.y*10))
    selected = adsk.core.ObjectCollection.create()
    for region in regions:
        area = region['area']
        x,y = region['centroid']
        def score(item):
            return abs(item[1]-area)/max(area,.01)+math.hypot(item[2]-x,item[3]-y)
        if not candidates:
            raise RuntimeError('Missing closed profile: '+str(region['centroid']))
        best = min(candidates,key=score)
        # Exact circle replaces its vector approximation: <=0.013 mm² delta.
        if abs(best[1]-area)>max(.02,area*1e-5) or math.hypot(best[2]-x,best[3]-y)>.02:
            raise RuntimeError('Profile mismatch: expected area/centroid %s/%s; got %s'%
                               (area,region['centroid'],best[1:]))
        selected.add(best[0])
        candidates.remove(best)
    logger.info('%s: matched %d vector regions; %d unselected hole profiles',
                sketch.name,selected.count,len(candidates))
    return selected


def build_design(app, regions, logger):
    import adsk.core
    import adsk.fusion
    doc = app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
    doc.name = '70 mm Camel and Panda Crest - Vectors'
    design = adsk.fusion.Design.cast(app.activeProduct)
    if not design:
        raise RuntimeError('New Fusion design unavailable.')
    design.designType = adsk.fusion.DesignTypes.DirectDesignType
    design.unitsManager.distanceDisplayUnits = adsk.fusion.DistanceUnits.MillimeterDistanceUnits
    root = design.rootComponent
    finishes = [make_appearance(app,design,name,rgb) for name,rgb in PALETTE]
    base_sketch = root.sketches.add(root.xYConstructionPlane)
    base_sketch.name = '70 mm substrate circle'
    base_sketch.sketchCurves.sketchCircles.addByCenterRadius(
        adsk.core.Point3D.create(0,0,0),DIAMETER_MM/20)
    base_height = (DISC_THICKNESS_MM-INLAY_THICKNESS_MM)/10
    extrudes = root.features.extrudeFeatures
    base_feature = extrudes.addSimple(base_sketch.profiles.item(0),
        adsk.core.ValueInput.createByReal(base_height),adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    base = base_feature.bodies.item(0)
    base.name = 'White substrate and flush white regions'
    base.appearance = finishes[0]
    base_sketch.isVisible = False
    plane_input = root.constructionPlanes.createInput()
    plane_input.setByOffset(root.xYConstructionPlane,adsk.core.ValueInput.createByReal(base_height))
    plane = root.constructionPlanes.add(plane_input)
    plane.name = 'Flush inlay floor - 1.6 mm'
    plane.isLightBulbOn = False
    for color,(name,rgb) in enumerate(PALETTE):
        polygons = [r for r in regions if r['color']==color]
        logger.info('Drawing %s: %d regions, %d vertices',name,len(polygons),
                    sum(len(ring) for r in polygons for ring in r['rings']))
        sketch = root.sketches.add(plane)
        sketch.name = name+' - closed vector regions'
        sketch.isComputeDeferred = True
        try:
            for polygon in polygons:
                for ring in polygon['rings']:
                    draw_ring(sketch,ring)
        finally:
            sketch.isComputeDeferred = False
        profiles = select_profiles(sketch,polygons,logger)
        operation = (adsk.fusion.FeatureOperations.JoinFeatureOperation if color==0
                     else adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
        feature = extrudes.addSimple(profiles,adsk.core.ValueInput.createByReal(INLAY_THICKNESS_MM/10),operation)
        for number,body in enumerate(feature.bodies):
            body.name = ('White substrate and flush white regions' if color==0
                         else '%s vector inlay %02d'%(name,number+1))
            body.appearance = finishes[color]
        sketch.isVisible = False
        logger.info('%s inlays complete; result bodies=%d',name,feature.bodies.count)
        adsk.doEvents()
    root.attributes.add('crest','dimensions_mm','70 diameter x 2 overall; five flush vector colors')
    root.attributes.add('crest','inlays_mm','1.6 white substrate + 0.4 color inlays')
    root.attributes.add('crest','artwork','Traced closed vector regions; no raster-color mesh.')
    expected = math.pi*(DIAMETER_MM/2)**2*DISC_THICKNESS_MM
    volume = sum(body.volume*1000 for body in root.bRepBodies)
    if abs(volume-expected)>.1:
        raise RuntimeError('Native solid volume differs from full disc: %.6f vs %.6f mm3'%(volume,expected))
    for body in root.bRepBodies:
        if not body.isSolid:
            raise RuntimeError('Non-solid vector inlay: '+body.name)
    box = root.preciseBoundingBox
    sizes = [(getattr(box.maxPoint,a)-getattr(box.minPoint,a))*10 for a in ('x','y','z')]
    if any(abs(a-b)>1e-4 for a,b in zip(sizes,[DIAMETER_MM,DIAMETER_MM,DISC_THICKNESS_MM])):
        raise RuntimeError('Unexpected crest dimensions: '+str(sizes))
    logger.info('VERIFIED: %d native solids; %d mesh bodies; bounds=%s mm; volume=%.6f mm3',
                root.bRepBodies.count,root.meshBodies.count,sizes,volume)
    app.activeViewport.fit()
    app.activeViewport.refresh()
    return design


def run(context):
    logger = logging.getLogger('crest')
    logger.setLevel(logging.INFO)
    logger.propagate = False
    for old in list(logger.handlers):
        logger.removeHandler(old)
        old.close()
    handler = logging.FileHandler(LOG_PATH,encoding='utf-8')
    handler.setFormatter(logging.Formatter('%(asctime)s %(levelname)s %(message)s'))
    logger.addHandler(handler)
    started = time.monotonic()
    app = None
    try:
        logger.info('RUN START: native vector crest, 70 x 70 x 2 mm; 0.4 mm flush color inlays')
        if not 0 < INLAY_THICKNESS_MM < DISC_THICKNESS_MM:
            raise ValueError('Inlay depth must leave a positive substrate.')
        import adsk.core
        app = adsk.core.Application.get()
        regions = load_vectors()
        logger.info('Fusion=%s; vector regions=%d; colors=%s',app.version,len(regions),
                    dict(Counter(r['color'] for r in regions)))
        design = build_design(app,regions,logger)
        notify = print if context=='mcp' else app.userInterface.messageBox
        notify('Created native vector crest: 70 mm round x 2 mm, five flush colors.\n'
               'Closed sketches and solid color inlays are editable in Fusion.\nLog: '+str(LOG_PATH))
    except Exception:
        logger.exception('Vector crest creation failed')
        raise
    finally:
        logger.info('RUN END %.2fs',time.monotonic()-started)
        logger.removeHandler(handler)
        handler.close()


